    @staticmethod
    def make_xip_elf(payload):
        load_addr = 0x10000000
        payload_off = 0x100

        elf_header = struct.pack(
            '<16sHHIIIIIHHHHHH',
            b'\x7fELF\x01\x01\x01' + b'\x00' * 9,
            2,          # ET_EXEC
            40,         # EM_ARM
            1,          # EV_CURRENT
            load_addr,
            52,         # e_phoff
            0,          # e_shoff
            0x05000200, # EABI version 5, soft-float
            52,         # e_ehsize
            32,         # e_phentsize
            1,          # e_phnum
            0,
            0,
            0,
        )
        phdr = struct.pack(
            '<IIIIIIII',
            1,          # PT_LOAD
            payload_off,
            load_addr,
            load_addr,
            len(payload),
            len(payload),
            5,          # PF_R | PF_X
            4,
        )

        return elf_header + phdr + bytes(payload_off - 84) + payload

